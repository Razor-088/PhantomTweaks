let logoCache: Record<string, string> = {};

export function getSteamHeaderUrl(gameName: string): string | null {
  const lower = gameName.toLowerCase();
  for (const [key, id] of Object.entries(GAME_STEAM_IDS)) {
    if (lower.includes(key) && id > 0) {
      return `https://cdn.akamai.steamstatic.com/steam/apps/${id}/header.jpg`;
    }
  }
  return null;
}

export async function loadGameLogo(name: string): Promise<string | null> {
  if (logoCache[name]) return logoCache[name];
  const url = getSteamHeaderUrl(name);
  if (!url) return null;
  logoCache[name] = url;
  return url;
}

export function preloadGameLogos(gameNames: string[]) {
  gameNames.forEach((name) => {
    if (!logoCache[name]) {
      loadGameLogo(name).catch(() => {});
    }
  });
}
