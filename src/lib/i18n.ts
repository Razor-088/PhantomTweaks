function fill(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

export function translate(lang: Lang, key: string, vars?: Vars): string {
  const dict = lang === 'en' ? en : es;
  let t = dict[key];
  if (t === undefined && lang === 'en') t = es[key];
  if (t === undefined) return key;
  return fill(t, vars);
}

export function useI18n() {
  const lang: Lang = useAppStore((s) => (s.settings?.language === 'en' ? 'en' : 'es'));
  return useMemo(
    () => ({
      lang,
      t: (key: string, vars?: Vars) => translate(lang, key, vars),
    }),
    [lang]
  );
}

export function useTweakMeta(id: string, fallbackName = '', fallbackDesc = '') {
  const { t } = useI18n();
  const name = t(`tweak.${id}.name`);
  const desc = t(`tweak.${id}.desc`);
  return {
    name: name.startsWith(`tweak.${id}.`) ? fallbackName : name,
    desc: desc.startsWith(`tweak.${id}.`) ? fallbackDesc : desc,
  };
}
